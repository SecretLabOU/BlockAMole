"""
params_spec.py -- hand-curated literature parameters (input to analysis.py).

Every row carries an EXACT quote copied from the PDF (or, for the GitHub field
report, the issue page) in raw/. analysis.py re-extracts the text of the cited
page from the raw file and checks that the quote occurs there (whitespace,
line-break hyphenation, ligatures and typographic quotes are normalised; see
analysis.py:norm_strict and match_quote). Rows whose quote cannot be found are
written with verified=False and make analysis.py exit non-zero.

Fields
  id            stable row id
  censor        which censor the value describes
  ptype         parameter type:
                  addr_discovery  - time from first use/exposure to probe or block
                  visibility      - fraction of connections/endpoints affected
                  persistence     - how long blocks last / unblocking
                  name_layer      - name blocklists, churn, list->block delays
                  collateral      - range/provider/protocol-wide blocking regimes
                  arrival         - proxy arrival/replenishment (game theory, Snowflake)
  parameter     short description of the quantity
  value         value or range as reported (no new arithmetic here; arithmetic
                lives in analysis.py:derived_values)
  units
  context       measurement context: years, vantage, protocol, method
  source        key into SOURCES (raw/ file)
  page          1-based page index in the raw PDF (or HTML locator)
  mode          'text' (pdftotext reading order), 'layout' (pdftotext -layout;
                used for table rows), or 'html' (GitHub issue JSON)
  quote         exact quote
  extra_quotes  optional list of further exact quotes from the same page/mode
                (used to verify every number transcribed from a table, or the
                sentence a value comes from); all must be found
  model         which model quantity it informs
  comparable    'yes' (comparable with the model quantity after a unit conversion),
                'partial' (comparable only with the caveats in note), or 'no'
                (not comparable with any model quantity)
  note          caveats
"""

