def _selftest():
    rng = np.random.default_rng(1)
    worst = 0.0
    for _ in range(40):
        m = int(rng.integers(1, 25))
        b = rng.uniform(0.05, 5, m)
        d = rng.uniform(0.05, 5, m)
        T = float(rng.uniform(0.1, 20))
        worst = max(worst, abs(bd_window(b, d, T) - bd_window_dense(b, d, T)))
    print(f"spectral vs dense expm (40 random chains): max |diff| = {worst:.2e}")
    # LinearCTMC vs birth-death on the constant pool
    ch = batch_name_chain(8, 1)
    for beta in (0.3, 0.661, 1.0, 1.7):
        w1 = ch.window(5.0, intro=1.0, disc=beta)
        w2 = name_window_constant(beta, 8, 5.0)
        assert abs(w1 - w2) < 1e-11, (w1, w2)
        assert abs(ch.timeavg(intro=1.0, disc=beta)
                   - (1 - pi0_geometric(beta, 8))) < 1e-12
    print("LinearCTMC(batch b=1) == birth-death pool: ok")
    # address stationary vs closed form
    for n in (1, 3, 8):
        b, d = addr_rates(n, 1.0, 3.0)
        pi = bd_stationary(b, d)
        assert abs(pi[0] - 0.25 ** n) < 1e-15
    print("address stationary P[c=0] = p^n: ok")
    # Krylov branch vs spectral branch on the same chains
    global _SPECTRAL_MAX
    old = _SPECTRAL_MAX
    worst = 0.0
    for m, beta, T in ((300, 1.0, 5.0), (1200, 0.9, 20.0), (600, 1.3, 1.0)):
        b, d = name_rates_constant(m, 1.0, beta)
        _SPECTRAL_MAX = 10 ** 6
        v1 = bd_window(b, d, T)
        _SPECTRAL_MAX = 10
        v2 = bd_window(b, d, T)
        worst = max(worst, abs(v1 - v2))
    _SPECTRAL_MAX = old
    print(f"spectral vs Krylov (m = 300..1200): max |diff| = {worst:.2e}")
    # strategic poisson == constant pool
    ch = strategic_chain(8, "poisson", r=2)
    w1 = ch.window(5.0, intro=1.0, disc=0.7)
    assert abs(w1 - name_window_constant(0.7, 8, 5.0)) < 1e-10
    print("strategic('poisson', r=2) == constant pool: ok")
    # providers P=kmax pooled == single pool
    ch = providers_chain(8, 1, "pooled")
    w1 = ch.window(5.0, intro=1.0, disc=0.8)
    assert abs(w1 - name_window_constant(0.8, 8, 5.0)) < 1e-10
    print("providers(P=8,kp=1,pooled) == constant pool: ok")
    # exposure rho=0 == single pool
    ch = exposure_chain(8, 0.0)
    w1 = ch.window(5.0, intro=1.0, disc=0.8, theta=1.0)
    assert abs(w1 - name_window_constant(0.8, 8, 5.0)) < 1e-10
    print("exposure(rho=0) == constant pool: ok")
    # sweep chain stationary
    Q = addr_sweep_generator(8, 1.0, 3.0, 1.0)
    pi = ctmc_stationary(Q)
    assert abs(pi[0] - 1.0 / (1.0 + 24.0)) < 1e-14
    print("sweep chain P[c=0] = lam_a/(lam_a + n mu): ok")
    print("self-test passed")


if __name__ == "__main__":
    _selftest()
