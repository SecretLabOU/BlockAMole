def batch_name_chain(kmax, b):
    """Constant-rate pool with bursty burns: events at rate lam_disc/b remove
    min(b, K) units (rotation_game.simulate_domain with burn_batch=b), so the
    mean burn throughput is lam_disc whenever K >= b.
    Rates: intro (mint), disc (burn-event rate, already divided by b)."""
    def trans(K):
        out = []
        if K < kmax:
            out.append((K + 1, "intro", 1.0))
        if K >= 1:
            out.append((max(0, K - b), "disc", 1.0 / b))
        return out
    return LinearCTMC(kmax, trans, lambda K: K >= 1)


def strategic_chain(kmax, policy, j=None, r=0):
    """Strategic-timing censor with an optional defender reserve.

    State (A, R, D): A active (served, discoverable) live units, R reserve
    units (live but never served, hence undiscoverable), D discovered-but-not-
    yet-blocked active units, 0 <= D <= A, A + R <= kmax, R <= r.

    Defender.  Mints at rate lam_intro while A + R < kmax. A mint goes to the
    active pool if A == 0, else to the reserve if R < r, else to the active
    pool ("serve from K - r units").  Whenever the active pool becomes empty
    and R > 0, all reserve units activate at once (A <- R, R <- 0, D <- 0).

    Censor.  Discovers undiscovered active units at aggregate rate lam_disc
    (while A - D >= 1); new units arrive undiscovered. On each discovery
    D <- D + 1 and the blocking policy decides whether to strike:
      'poisson'      block each unit on discovery (equals the constant-rate
                     pool of the paper);
      'batch'        strike (block all D discovered units) when D == j; if the
                     pool can never reach j discovered units the censor waits
                     for more mints;
      'batch_or_all' strike when D == j or when D == A (all active discovered);
      'strike_all'   strike when D == A, i.e. the whole active pool is
                     discovered (blocking it empties the active pool).
    The system is up iff A >= 1.
    Rates: intro, disc.
    """
    if policy not in ("poisson", "batch", "batch_or_all", "strike_all"):
        raise ValueError(policy)
    if policy in ("batch", "batch_or_all") and (j is None or j < 1):
        raise ValueError("batch policies need j >= 1")

    def block(A, R, D, nb):
        A, D = A - nb, D - nb
        if A == 0 and R > 0:
            A, R, D = R, 0, 0
        return (A, R, D)

    def trans(s):
        A, R, D = s
        out = []
        if A + R < kmax:
            if A == 0:
                ns = (1, R, D)
            elif R < r:
                ns = (A, R + 1, D)
            else:
                ns = (A + 1, R, D)
            out.append((ns, "intro", 1.0))
        if A - D >= 1:
            D2 = D + 1
            if policy == "poisson":
                ns = block(A, R, D2, 1)
            elif policy == "batch":
                ns = block(A, R, D2, D2) if D2 == j else (A, R, D2)
            elif policy == "batch_or_all":
                ns = block(A, R, D2, D2) if (D2 == j or D2 == A) else (A, R, D2)
            else:  # strike_all
                ns = block(A, R, D2, D2) if D2 == A else (A, R, D2)
            out.append((ns, "disc", 1.0))
        return out

    return LinearCTMC((0, 0, 0), trans, lambda s: s[0] >= 1)


def censor_best_response_timeavg(kmax, lam_intro, lam_disc, tol=1e-13,
                                 max_iter=500000):
    """Best timing policy against the time-average metric (no reserve).

    Average-reward MDP on states (A, D), 0 <= D <= A <= kmax (A live units,
    D of them discovered but unblocked). Events: mint (rate lam_intro while
    A < kmax, arrives undiscovered) and discovery (rate lam_disc while
    A - D >= 1). After every event the censor, who observes (A, D), may block
    any number b <= D of the discovered units. Reward rate 1{A = 0}; the censor
    maximizes the long-run fraction of time the pool is empty. Solved by
    relative value iteration on the uniformized chain (rate lam_intro +
    lam_disc; self-loops make it aperiodic).

    Returns dict(g=optimal down fraction, policy=b[A,D] array (pre-decision
    state), iterations, span).
    """
    K = kmax
    Lam = lam_intro + lam_disc
    pi_, pd_ = lam_intro / Lam, lam_disc / Lam
    valid = np.tril(np.ones((K + 1, K + 1), dtype=bool))      # D <= A
    r = np.zeros((K + 1, K + 1))
    r[0, 0] = 1.0
    V = np.zeros((K + 1, K + 1))
    A_idx, D_idx = np.nonzero(valid)
    mintA = np.where(A_idx < K, A_idx + 1, A_idx)
    discD = np.where(A_idx - D_idx >= 1, D_idx + 1, D_idx)

    def best_post(V):
        """M[A,D] = max_{b<=D} V[A-b, D-b] and the maximizing b (ties -> fewer
        blocks)."""
        M = np.full_like(V, -np.inf)
        arg = np.zeros(V.shape, dtype=int)
        for A in range(K + 1):
            for D in range(A + 1):
                if D == 0:
                    M[A, D], arg[A, D] = V[A, D], 0
                else:
                    if V[A, D] >= M[A - 1, D - 1] - 1e-15:
                        M[A, D], arg[A, D] = V[A, D], 0
                    else:
                        M[A, D], arg[A, D] = M[A - 1, D - 1], arg[A - 1, D - 1] + 1
        return M, arg

    # diagonals c = A - D: blocking b units moves (A,D) -> (A-b, D-b) along
    # the same diagonal, so M is a running maximum along each diagonal
    diags = [(np.arange(c, K + 1), np.arange(0, K + 1 - c)) for c in range(K + 1)]

    def best_post_value(V):
        M = np.empty_like(V)
        for a_i, d_i in diags:
            M[a_i, d_i] = np.maximum.accumulate(V[a_i, d_i])
        return M

    it, span = 0, np.inf
    g = None
    while it < max_iter:
        it += 1
        M = best_post_value(V)
        TV = np.zeros_like(V)
        TV[A_idx, D_idx] = (r[A_idx, D_idx] + pi_ * M[mintA, D_idx]
                            + pd_ * M[A_idx, discD])
        diff = (TV - V)[valid]
        span = diff.max() - diff.min()
        g = 0.5 * (diff.max() + diff.min())
        V = TV - TV[0, 0]
        V[~valid] = 0.0
        if span < tol:
            break
    M, arg = best_post(V)
    pol = np.where(valid, arg, -1)
    return {"g": float(g), "policy": pol, "iterations": it, "span": float(span)}


def policy_chain(kmax, policy):
    """CTMC of the (A, D) pool under a deterministic blocking policy
    policy[A, D] = number of discovered units blocked right after an event
    leaves the pool in pre-decision state (A, D). Rates: intro, disc."""
    def post(A, D):
        b = int(policy[A, D])
        return (A - b, D - b)

    def trans(s):
        A, D = s
        out = []
        if A < kmax:
            out.append((post(A + 1, D), "intro", 1.0))
        if A - D >= 1:
            out.append((post(A, D + 1), "disc", 1.0))
        return out
    return LinearCTMC((0, 0), trans, lambda s: s[0] >= 1)


def providers_chain(P, kp, mode):
    """P providers with kp slots each; state = occupancy counts (n_0..n_kp),
    n_l = number of providers holding l live units (sum n_l = P).

    mode 'pooled' (the model the paper uses): mints at total rate lam_intro go
      to a uniformly chosen non-full provider; takedowns at total rate lam_disc
      hit a uniformly chosen NON-EMPTY provider and empty it (full-capacity
      censor).
    mode 'idle', the idle-clock model (E9), read as provider-initiated
      suspensions: every provider has its own mint clock lam_intro/P (while not
      full) and its own takedown clock lam_disc/P (while non-empty); a takedown
      empties it.
    The system is up iff some provider holds a live unit.
    Rates: intro, disc.
    """
    if mode not in ("pooled", "idle"):
        raise ValueError(mode)

    def trans(s):
        out = []
        nf = sum(s[:kp])
        ne = sum(s[1:])
        for lvl in range(kp):
            if s[lvl] > 0:
                w = s[lvl] / nf if mode == "pooled" else s[lvl] / P
                t = list(s)
                t[lvl] -= 1
                t[lvl + 1] += 1
                out.append((tuple(t), "intro", w))
        for lvl in range(1, kp + 1):
            if s[lvl] > 0:
                w = s[lvl] / ne if mode == "pooled" else s[lvl] / P
                t = list(s)
                t[lvl] -= 1
                t[0] += 1
                out.append((tuple(t), "disc", w))
        return out

    init = (P,) + (0,) * kp
    return LinearCTMC(init, trans, lambda s: s[0] < P)


def exposure_chain(kmax, rho):
    """Mint-time exposure: state (E, U), E exposed and U unexposed live units,
    E + U <= kmax. A mint (rate lam_intro while E+U < kmax) is exposed with
    probability rho; exposed units are burned pre-emptively at per-unit rate
    theta; usage burns (aggregate rate lam_disc while E+U >= 1) hit a uniformly
    random live unit. Up iff E + U >= 1. Rates: intro, disc, theta.
    (theta = infinity is the single pool with intro rate (1-rho) lam_intro;
    see exposure_window_inf.)"""
    def trans(s):
        E, U = s
        out = []
        if E + U < kmax:
            out.append(((E + 1, U), "intro", rho))
            out.append(((E, U + 1), "intro", 1.0 - rho))
        if E > 0:
            out.append(((E - 1, U), "theta", float(E)))
        L = E + U
        if L >= 1:
            out.append(((E - 1, U), "disc", E / L))
            out.append(((E, U - 1), "disc", U / L))
        return out
    return LinearCTMC((0, 0), trans, lambda s: s[0] + s[1] >= 1)


def addr_sweep_generator(n, lam_a, mu, s):
    """Address layer with synchronized discovery. Each endpoint is discovered at
    total rate lam_a: individually at rate (1-s) lam_a and through a sweep
    (one event that blocks every clear endpoint at once) at rate s*lam_a, so
    each endpoint's marginal is still the two-state chain (lam_a, mu).
    c -> c+1 at mu (n-c); c -> c-1 at (1-s) lam_a c; c -> 0 at s lam_a (c>=1).
    Returns a dense generator on {0..n}."""
    Q = np.zeros((n + 1, n + 1))
    for c in range(n + 1):
        if c < n:
            Q[c, c + 1] += mu * (n - c)
        if c >= 1:
            Q[c, c - 1] += (1.0 - s) * lam_a * c
            Q[c, 0] += s * lam_a
    np.fill_diagonal(Q, 0.0)
    np.fill_diagonal(Q, -Q.sum(axis=1))
    return Q


# =========================================================================== #
#  4. Range blocking of a provider's address space (crisis regime)
# =========================================================================== #
def p_range(g, lam_a, mu):
    """Per-endpoint blocked probability when a fraction g of the provider's
    address space is range-blocked and each rotation draws a fresh address
    uniformly from that space:  p(g) = g + (1-g) lam_a/(lam_a+mu)
                                     = (lam_a + mu g)/(lam_a + mu).
    Derivation: an endpoint leaves 'clear' at rate lam_a + mu g (discovery, or
    a rotation that lands in the blocked range) and leaves 'blocked' at rate
    mu (1-g) (a rotation that lands in clear space), so it is the two-state
    chain with rates (lam_a + mu g, mu (1-g))."""
    g = float(g)
    return (lam_a + mu * g) / (lam_a + mu)


def address_factor_providers(gs, ns, lam_a, mu):
    """Time-average address factor 1 - prod_i p(g_i)^{n_i} for endpoints split
    over providers with (independent) range-blocked fractions g_i.
    gs, ns: sequences (per provider). Endpoints are independent, so the joint
    all-blocked probability is the product of per-endpoint probabilities."""
    logp = 0.0
    for g, k in zip(gs, ns):
        p = p_range(g, lam_a, mu)
        if k > 0:
            if p <= 0:
                return 1.0
            logp += k * np.log(p)
    return float(1.0 - np.exp(logp))


def address_factor_regime(g_crisis, pi_c, n, P, lam_a, mu, mode="common",
                          g_normal=0.0):
    """Regime-averaged address factor with crisis fraction pi_c.

    n endpoints are split evenly over P providers (n must be divisible by P).
    mode 'common': all providers are in crisis together a fraction pi_c of the
      time (e.g. a national range-blocking order):
        (1-pi_c) A(g_normal) + pi_c A(g_crisis).
    mode 'independent': each provider is independently in crisis a fraction
      pi_c of the time (provider-specific blocking):
        sum_m Binom(m; P, pi_c) [1 - p(g_c)^{m n/P} p(g_n)^{(P-m) n/P}].
    Plug measured range-blocked fractions in as g_crisis / g_normal."""
    if n % P:
        raise ValueError("n must be divisible by P")
    k = n // P
    if mode == "common":
        a_n = address_factor_providers([g_normal] * P, [k] * P, lam_a, mu)
        a_c = address_factor_providers([g_crisis] * P, [k] * P, lam_a, mu)
        return (1.0 - pi_c) * a_n + pi_c * a_c
    if mode == "independent":
        from scipy.stats import binom
        tot = 0.0
        for m in range(P + 1):
            gs = [g_crisis] * m + [g_normal] * (P - m)
            tot += binom.pmf(m, P, pi_c) * address_factor_providers(
                gs, [k] * P, lam_a, mu)
        return float(tot)
    raise ValueError(mode)


def addr_window_range(g, n, lam_a, mu, T):
    """Address-layer window probability on one provider with range-blocked
    fraction g: the clear-count chain with discovery rate lam_a + mu g and
    recovery rate mu (1-g) per endpoint."""
    if g >= 1:
        return 0.0 if np.ndim(T) == 0 else np.zeros(np.shape(T))
    return addr_window(n, lam_a + mu * g, mu * (1.0 - g), T)


def addr_window_providers(gs, ns, lam_a, mu, T):
    """Address-layer window probability with endpoints split over providers
    with range-blocked fractions g_i (independent providers). Builds the joint
    clear-count chain (Kronecker sum of the per-provider chains); the only
    down state is 'every endpoint blocked'."""
    gens = []
    for g, k in zip(gs, ns):
        if k == 0:
            continue
        la, m = lam_a + mu * g, mu * (1.0 - g)
        Q = np.zeros((k + 1, k + 1))
        for c in range(k + 1):
            if c < k:
                Q[c, c + 1] = m * (k - c)
            if c > 0:
                Q[c, c - 1] = la * c
        np.fill_diagonal(Q, -Q.sum(axis=1))
        gens.append(sp.csr_matrix(Q))
    Qj = gens[0]
    for G in gens[1:]:
        Qj = sp.kronsum(G, Qj, format="csr")    # kronsum(A,B) = A(x)I + I(x)B
    N = Qj.shape[0]
    up = np.ones(N, dtype=bool)
    up[0] = False                               # all counts zero is index 0
    return ctmc_window(Qj.tocsr(), up, T)


