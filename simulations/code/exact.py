"""
exact.py -- Exact continuous-time Markov chain (CTMC) tools for the rotation game.

Everything the event-driven simulator (rotation_game.py) estimates by Monte Carlo
can be computed exactly for the same Markov model.

  * time-average availability    = stationary P[up]
  * (alpha,T)-interval availability = P[up throughout [0,T]] for a chain started
    in stationarity
        = pi_U  expm(Q_UU T)  1,
    where U is the set of up states, pi_U the stationary probabilities of those
    states, and Q_UU the generator restricted to U (transitions into the down
    set are killed).  This is exactly the quantity the simulator's
    interval_up_probability() estimates (the fraction of window start times t0
    such that [t0, t0+T] contains no down time).

The address layer and the name layer of the model are driven by independent
clocks, so the system is up throughout a window iff both layers are, and

    interval availability = window_addr(T) * window_name(T),
    time-average availability = P[addr up] * P[name up].

Two numerical engines are provided.

  1. Birth-death chains (address layer, constant-rate and per-unit name pools,
     range-blocked address layer). These chains are reversible, so the killed
     generator is similar to a symmetric tridiagonal matrix:
        S = D^{1/2} Q_UU D^{-1/2},   D = diag(pi_U),
     and   pi_U expm(Q_UU T) 1 = s' expm(S T) s,  s = sqrt(pi_U)
                               = sum_m (v_m' s)^2 exp(lambda_m T).
     All weights are non-negative and the eigenvalues are negative, so the
     result is accurate to ~1e-14 absolute and cheap for many T at once.
     The stationary law is computed by detailed balance in log space.

  2. General chains (batch burns, strategic timing censor, providers, mint-time
     exposure, synchronized address discovery). The state space is generated by
     breadth-first search from an initial state, the off-diagonal generator is
     stored as a sum of sparse matrices that are linear in the named rate
     parameters (so a sweep over beta only rescales them), the stationary law is
     a direct (dense or sparse LU) solve, and the window probability uses
     scipy's expm (small chains) or expm_multiply (large chains).

Time unit: 1/lam_intro (lam_intro = 1) throughout, as in the paper.

Run `python3 exact.py` for a self-test (spectral vs dense expm, closed forms).
"""

from collections import deque

import numpy as np
import scipy.sparse as sp
from scipy.integrate import quad
from scipy.linalg import eigh_tridiagonal, expm
from scipy.optimize import brentq
from scipy.sparse.linalg import expm_multiply, spsolve
from scipy.special import logsumexp

# chains larger than this use sparse/Krylov routines instead of dense ones
_DENSE_MAX = 400
_SPECTRAL_MAX = 200     # above this the Krylov path is faster (same accuracy)


# =========================================================================== #
#  1. Birth-death chains on {0,...,m}, down set = {0}
# =========================================================================== #
def _as_rates(births, deaths):
    b = np.asarray(births, dtype=float).ravel()
    d = np.asarray(deaths, dtype=float).ravel()
    if b.shape != d.shape:
        raise ValueError("births and deaths must have the same length m")
    if np.any(b < 0) or np.any(d < 0):
        raise ValueError("rates must be non-negative")
    return b, d


def bd_log_stationary(births, deaths):
    """log of the stationary law of a birth-death chain on {0..m}.

    births[i] is the rate i -> i+1 and deaths[i] the rate i+1 -> i
    (i = 0..m-1). All rates must be positive (irreducible chain).
    Detailed balance: pi_{i+1} = pi_i * births[i] / deaths[i].
    """
    b, d = _as_rates(births, deaths)
    if np.any(b <= 0) or np.any(d <= 0):
        raise ValueError("bd_log_stationary needs strictly positive rates")
    logpi = np.zeros(len(b) + 1)
    logpi[1:] = np.cumsum(np.log(b) - np.log(d))
    return logpi - logsumexp(logpi)


def bd_stationary(births, deaths):
    """Stationary law of a birth-death chain on {0..m} (see bd_log_stationary).
    Degenerate cases: all deaths zero -> point mass at m; all births zero ->
    point mass at 0."""
    b, d = _as_rates(births, deaths)
    m = len(b)
    if np.all(d == 0) and np.all(b > 0):
        pi = np.zeros(m + 1)
        pi[m] = 1.0
        return pi
    if np.all(b == 0) and np.all(d > 0):
        pi = np.zeros(m + 1)
        pi[0] = 1.0
        return pi
    return np.exp(bd_log_stationary(b, d))


def _bd_killed_tridiag(b, d):
    """Diagonal and symmetrized off-diagonal of the killed generator on 1..m."""
    m = len(b)
    birth_from = np.append(b[1:], 0.0)       # birth from state i = 1..m
    death_from = d                            # death from state i = 1..m (d[i-1])
    diag = -(birth_from + death_from)
    off = np.sqrt(b[1:] * d[1:])              # S[i,i+1] = sqrt(b_i d_i), i = 1..m-1
    return diag, off


def bd_window(births, deaths, T):
    """P[state >= 1 throughout [0,T]] for a stationary birth-death chain.

    births[i]: rate i -> i+1, deaths[i]: rate i+1 -> i (i = 0..m-1); the down
    set is {0}. T may be a scalar or an array. Uses the symmetric spectral
    form (exact up to rounding) for m <= 200 and a Krylov expm-vector product
    on the symmetrized matrix for larger m.
    """
    b, d = _as_rates(births, deaths)
    Ts = np.atleast_1d(np.asarray(T, dtype=float))
    scalar = np.ndim(T) == 0
    m = len(b)
    # degenerate chains
    if np.all(d == 0) and np.all(b > 0):          # never moves down -> always up
        out = np.ones_like(Ts)
        return float(out[0]) if scalar else out
    if np.all(b == 0) and np.all(d > 0):          # absorbed at 0 -> always down
        out = np.zeros_like(Ts)
        return float(out[0]) if scalar else out
    logpi = bd_log_stationary(b, d)
    s = np.exp(0.5 * logpi[1:])                   # sqrt(pi_U)
    diag, off = _bd_killed_tridiag(b, d)
    if m == 1:
        out = s[0] ** 2 * np.exp(min(diag[0], 0.0) * Ts)
    elif m <= _SPECTRAL_MAX:
        lam, V = eigh_tridiagonal(diag, off)
        lam = np.minimum(lam, 0.0)                # killed chain: lam < 0 exactly
        w = (V.T @ s) ** 2
        out = np.exp(np.outer(Ts, lam)) @ w
    else:
        S = sp.diags([off, diag, off], [-1, 0, 1], format="csr")
        out = np.array([float(s @ expm_multiply(S * t, s)) for t in Ts])
    out = np.clip(out, 0.0, 1.0)
    return float(out[0]) if scalar else out


def bd_window_dense(births, deaths, T):
    """Reference implementation with a dense matrix exponential (for tests)."""
    b, d = _as_rates(births, deaths)
    pi = np.exp(bd_log_stationary(b, d))
    m = len(b)
    Q = np.zeros((m + 1, m + 1))
    for i in range(m):
        Q[i, i + 1] = b[i]
        Q[i + 1, i] = d[i]
    np.fill_diagonal(Q, -Q.sum(axis=1))
    QUU = Q[1:, 1:]
    return float(pi[1:] @ expm(QUU * T) @ np.ones(m))


# ---- the two layers of the paper's model ---------------------------------- #
def addr_rates(n, lam_a, mu):
    """Address layer: c = number of clear endpoints in {0..n}.
    c -> c+1 at mu*(n-c) (rotation away from a blocked address),
    c -> c-1 at lam_a*c (discovery and block of a clear address)."""
    c = np.arange(n)
    return mu * (n - c), lam_a * (c + 1.0)


def addr_window(n, lam_a, mu, T):
    """Address-layer window probability P[>=1 clear address throughout [0,T]]."""
    b, d = addr_rates(n, lam_a, mu)
    return bd_window(b, d, T)


def addr_timeavg(n, lam_a, mu):
    """Address factor c_a = 1 - (lam_a/(lam_a+mu))^n (Lemma 1)."""
    if lam_a <= 0:
        return 1.0
    return 1.0 - (lam_a / (lam_a + mu)) ** n


def name_rates_constant(kmax, lam_intro, lam_disc):
    """Constant-rate pool (Proposition: name pool): K -> K+1 at lam_intro
    (K<kmax), K -> K-1 at lam_disc (K>=1)."""
    return np.full(kmax, float(lam_intro)), np.full(kmax, float(lam_disc))


def name_rates_perunit(kmax, lam_intro, delta):
    """Per-unit discovery pool (the paper's per-name burn rates): K -> K-1 at
    delta*K."""
    return np.full(kmax, float(lam_intro)), delta * np.arange(1.0, kmax + 1)


def pi0_geometric(beta, kmax):
    """Closed-form P[K=0] = 1/sum_{i=0}^{kmax} beta^{-i}, evaluated in log space
    (valid for every beta > 0, including beta = 1)."""
    if beta <= 0:
        return 0.0
    i = np.arange(kmax + 1)
    return float(np.exp(-logsumexp(-i * np.log(beta))))


def meanK_geometric(beta, kmax):
    """E[K] of the constant-rate pool, pi_k proportional to beta^{-k}."""
    if beta <= 0:
        return float(kmax)
    i = np.arange(kmax + 1)
    lw = -i * np.log(beta)
    w = np.exp(lw - logsumexp(lw))
    return float(w @ i)


def name_window_constant(beta, kmax, T, lam_intro=1.0):
    if beta <= 0:
        return 1.0 if np.ndim(T) == 0 else np.ones(np.shape(T))
    b, d = name_rates_constant(kmax, lam_intro, beta * lam_intro)
    return bd_window(b, d, T)


def name_window_perunit(delta, kmax, T, lam_intro=1.0):
    if delta <= 0:
        return 1.0 if np.ndim(T) == 0 else np.ones(np.shape(T))
    b, d = name_rates_perunit(kmax, lam_intro, delta)
    return bd_window(b, d, T)


def timeavg_availability(beta, kmax, n, lam_a, mu):
    """Closed-form time-average availability (Theorem closedform)."""
    return (1.0 - pi0_geometric(beta, kmax)) * addr_timeavg(n, lam_a, mu)


def interval_availability(beta, kmax, T, n, lam_a, mu, lam_intro=1.0):
    """Exact interval availability of the paper's canonical model."""
    return (name_window_constant(beta, kmax, T, lam_intro)
            * addr_window(n, lam_a, mu, T))


# =========================================================================== #
#  2. General CTMCs, linear in named rate parameters
# =========================================================================== #
class LinearCTMC:
    """A finite CTMC whose off-diagonal rates are linear in named parameters.

    transitions(state) returns an iterable of (next_state, component, weight):
    the transition fires at rate  weight * rates[component].  The reachable
    state space is generated once by breadth-first search from `initial`
    (only transitions with weight > 0 are followed), so it must not depend on
    the parameter values (true whenever all rate parameters are positive).
    up(state) -> bool marks the up states.
    """

    def __init__(self, initial, transitions, up, max_states=200000):
        states = [initial]
        index = {initial: 0}
        trip = {}                                  # comp -> (rows, cols, vals)
        queue = deque([initial])
        while queue:
            s = queue.popleft()
            i = index[s]
            for t, comp, w in transitions(s):
                if w <= 0 or t == s:
                    continue
                if t not in index:
                    index[t] = len(states)
                    states.append(t)
                    queue.append(t)
                    if len(states) > max_states:
                        raise RuntimeError("state space too large")
                r, c, v = trip.setdefault(comp, ([], [], []))
                r.append(i)
                c.append(index[t])
                v.append(float(w))
        N = len(states)
        self.states = states
        self.index = index
        self.N = N
        self.M = {comp: sp.csr_matrix((v, (r, c)), shape=(N, N))
                  for comp, (r, c, v) in trip.items()}
        self.up = np.array([bool(up(s)) for s in states])

    # -- assembly --------------------------------------------------------- #
    def Q(self, **rates):
        missing = set(self.M) - set(rates)
        if missing:
            raise ValueError(f"missing rate parameters: {sorted(missing)}")
        off = sp.csr_matrix((self.N, self.N))
        for comp, M in self.M.items():
            if rates[comp] != 0:
                off = off + rates[comp] * M
        out = np.asarray(off.sum(axis=1)).ravel()
        return (off - sp.diags(out)).tocsr()

    def stationary(self, **rates):
        return ctmc_stationary(self.Q(**rates))

    def timeavg(self, **rates):
        return float(self.stationary(**rates)[self.up].sum())

    def window(self, T, **rates):
        Q = self.Q(**rates)
        return ctmc_window(Q, self.up, T)

    def flux(self, comp, reward, **rates):
        """Stationary rate of transitions of component `comp`, each weighted by
        reward(state, next_state) (e.g. the number of units removed)."""
        Q = self.Q(**rates)
        pi = ctmc_stationary(Q)
        M = self.M[comp].tocoo()
        tot = 0.0
        for i, j, w in zip(M.row, M.col, M.data):
            tot += pi[i] * w * rates[comp] * reward(self.states[i], self.states[j])
        return tot


def ctmc_stationary(Q):
    """Stationary law of an irreducible CTMC with generator Q (dense or sparse).
    Solves pi Q = 0 with the last balance equation replaced by sum(pi) = 1."""
    N = Q.shape[0]
    if N == 1:
        return np.ones(1)
    if N <= _DENSE_MAX:
        A = (Q.toarray() if sp.issparse(Q) else np.asarray(Q)).T.copy()
        A[-1, :] = 1.0
        rhs = np.zeros(N)
        rhs[-1] = 1.0
        pi = np.linalg.solve(A, rhs)
    else:
        A = sp.csr_matrix(Q).T.tocsr()
        A = sp.vstack([A[:-1, :], sp.csr_matrix(np.ones((1, N)))]).tocsc()
        rhs = np.zeros(N)
        rhs[-1] = 1.0
        pi = spsolve(A, rhs)
    if pi.min() < -1e-9:
        raise RuntimeError(f"stationary solve produced negative mass {pi.min():.2e}")
    pi = np.clip(pi, 0.0, None)
    return pi / pi.sum()


def ctmc_window(Q, up_mask, T, pi=None):
    """pi_U expm(Q_UU T) 1 for a stationary CTMC (T scalar or array)."""
    if pi is None:
        pi = ctmc_stationary(Q)
    U = np.flatnonzero(up_mask)
    Ts = np.atleast_1d(np.asarray(T, dtype=float))
    scalar = np.ndim(T) == 0
    if len(U) == 0:
        out = np.zeros_like(Ts)
    else:
        if sp.issparse(Q):
            QUU = Q[U][:, U]
        else:
            QUU = sp.csr_matrix(np.asarray(Q)[np.ix_(U, U)])
        ones = np.ones(len(U))
        piU = pi[U]
        out = np.empty_like(Ts)
        for k, t in enumerate(Ts):
            if len(U) <= _DENSE_MAX:
                u = expm(QUU.toarray() * t) @ ones
            else:
                u = expm_multiply(QUU * t, ones)
            out[k] = piU @ u
    out = np.clip(out, 0.0, 1.0)
    return float(out[0]) if scalar else out


