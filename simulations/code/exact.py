#  5. Frontiers by root finding
# =========================================================================== #
def beta_star(avail, alpha, lo=1e-6, hi=2.0, hi_max=1e4, xtol=1e-10):
    """Largest beta with avail(beta) >= alpha, for avail decreasing in beta.

    Returns (beta_star, status): status 'ok', 'none' (avail(lo) < alpha: no
    beta > 0 suffices) or 'above' (avail(hi_max) >= alpha)."""
    if avail(lo) < alpha:
        return None, "none"
    while avail(hi) >= alpha:
        hi *= 2.0
        if hi > hi_max:
            return None, "above"
    root = brentq(lambda b: avail(b) - alpha, lo, hi, xtol=xtol, rtol=1e-13,
                  maxiter=500)
    return float(root), "ok"


def check_single_crossing(avail, alpha, root, lo=1e-3, npts=60):
    """Evaluate avail on a grid around the root and confirm one sign change.
    Returns True if avail - alpha is >= 0 left of the root and <= 0 right."""
    if root is None:
        return None
    grid = np.unique(np.concatenate([
        np.linspace(max(lo, 0.02 * root), root * 0.999, npts // 2),
        np.linspace(root * 1.001, 3.0 * root + 0.5, npts // 2)]))
    vals = np.array([avail(b) for b in grid]) - alpha
    left = vals[grid < root]
    right = vals[grid > root]
    return bool(np.all(left >= -1e-12) and np.all(right <= 1e-12))


def frontier_interval(alpha, T, n, lam_a, mu, kmax, lam_intro=1.0):
    """Convenience: exact interval frontier beta*(alpha, T) of the canonical
    model (constant-rate pool, independent address layer) for any rates.
    Rates are in any common unit; T in the same time unit. Returns
    (beta*, status) with status 'ok', 'none' or 'above' (see beta_star)."""
    aT = addr_window(n, lam_a, mu, T)
    if aT <= alpha:
        return None, "none"
    f = lambda b: name_window_constant(b, kmax, T, lam_intro) * aT
    return beta_star(f, alpha)


def frontier_timeavg(alpha, n, lam_a, mu, kmax):
    """Convenience alias for beta_star_avg with the argument order of
    frontier_interval (time-average frontier, closed form)."""
    return beta_star_avg(alpha, kmax, n, lam_a, mu)


def beta_star_avg(alpha, kmax, n, lam_a, mu):
    """Time-average frontier beta*_avg (Theorem frontier): the root of
    (1 - pi0(beta, kmax)) c_a = alpha (closed-form availability, numerically
    exact root). Returns (value, status)."""
    ca = addr_timeavg(n, lam_a, mu)
    if ca <= alpha:
        return None, "none"
    return beta_star(lambda b: (1.0 - pi0_geometric(b, kmax)) * ca, alpha)


