#  6. Discovery-delay Laplace transform (general discovery, Lemma general)
# =========================================================================== #
def laplace_from_cdf(cdf, mu, breakpoints=()):
    """p = E[exp(-mu D)] = P(D < I), I ~ Exp(mu), computed as
    int_0^inf mu e^{-mu x} F(x) dx (bounded integrand, robust quadrature)."""
    f = lambda x: mu * np.exp(-mu * x) * cdf(x)
    pts = sorted(set([0.0] + [float(b) for b in breakpoints if b > 0]))
    total, err = 0.0, 0.0
    edges = pts + [np.inf]
    for a, b in zip(edges[:-1], edges[1:]):
        v, e = quad(f, a, b, limit=400, epsabs=1e-13, epsrel=1e-11)
        total += v
        err += e
    return total, err


